"""Render the benchmark prompts into each model's exact final text, for the phone apps.

Usage (from the repository root):
    uv run eval/render_prompts.py

Every model expects its messages wrapped in its own chat template, and thinking
is switched off inside that template. llama-server does this using a template
engine that the phone libraries don't include. So we let the server produce the
final text once and ship it in spec/rendered_prompts.json. The apps then only
need to tokenize it, and receive exactly what the laptop benchmarks received.

Re-run this only when spec/bench_prompts.json changes: Llama's template includes
today's date, so running it again changes the file for no real reason.
"""

import json
import sys
import urllib.request

from benchmark import PROMPTS_PATH, engine_info
from llama_server import REPO_ROOT, LlamaServer, ServerError, available_builds, gguf_path, load_registry

OUTPUT_PATH = REPO_ROOT / "spec" / "rendered_prompts.json"


def post(server: LlamaServer, path: str, body: dict) -> dict:
    request = urllib.request.Request(
        f"{server.url}{path}", data=json.dumps(body).encode(), headers={"Content-Type": "application/json"}
    )
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.load(response)


def render_model(key: str, spec: dict) -> dict:
    """The final text of every prompt for one model, with its token count."""
    # Rendering doesn't depend on the backend, and every machine has the CPU build.
    rendered = {}
    with LlamaServer(gguf_path(key), build="cpu") as server:
        for prompt in spec["prompts"]:
            messages = [{"role": "system", "content": spec["system"]}, {"role": "user", "content": prompt["user"]}]
            text = post(server, "/apply-template", {"messages": messages})["prompt"]
            tokens = post(server, "/tokenize", {"content": text, "add_special": True, "parse_special": True})["tokens"]
            # The apps tokenize this text themselves. If they don't get this
            # count, their input differs from the laptop's.
            rendered[prompt["id"]] = {"text": text, "tokens": len(tokens)}
    return rendered


def main() -> int:
    if "cpu" not in available_builds():
        print("error: the CPU build of llama.cpp is missing. Run eval/build_llama_cpp.sh.", file=sys.stderr)
        return 1
    models = load_registry()
    missing = [key for key in models if not gguf_path(key).exists()]
    if missing:
        print(f"error: not downloaded: {', '.join(missing)}. Run models/download.py --all.", file=sys.stderr)
        return 1

    spec = json.loads(PROMPTS_PATH.read_text())
    engine = engine_info(LlamaServer(gguf_path(next(iter(models))), build="cpu"))
    output = {
        "description": "Generated by eval/render_prompts.py from spec/bench_prompts.json. Do not edit by hand.",
        "prompts_version": spec["version"],
        "llama_cpp_tag": engine["llama_cpp_tag"],
        "max_tokens": spec["max_tokens"],
        "prompt_ids": [prompt["id"] for prompt in spec["prompts"]],
        "models": {},
    }
    try:
        for key in models:
            print(f"{key}...", flush=True)
            output["models"][key] = render_model(key, spec)
    except ServerError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1

    OUTPUT_PATH.write_text(json.dumps(output, indent=2, ensure_ascii=False) + "\n")
    print(f"Wrote {OUTPUT_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
