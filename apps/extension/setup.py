"""Prepare the Wilo Chrome extension so it can be loaded in Chrome.

Usage (from the repository root):
    uv run apps/extension/setup.py

Does two things:
1. Downloads wllama (llama.cpp compiled to WebAssembly) at a pinned version,
   checks it against its published checksum, and copies the two files the
   extension needs into vendor/.
2. Writes generated/config.js: Wilo's rules (from spec/wilo_prompt.json) and
   the model download links (from models/registry.yaml), so the extension uses
   exactly the same prompt and model files as the benchmarks and training data.

Both folders are git-ignored; re-run this after changing either source file.

    uv run apps/extension/setup.py --zip

also packs the ready-to-load extension into dist/wilo-extension-<version>.zip,
the file testers get: the `wilo-extension` folder to load in Chrome, and
"Wilo tester guide.html" (guide/tester-guide.html with its pictures built in).
"""

import argparse
import base64
import hashlib
import io
import json
import tarfile
import urllib.request
import zipfile
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parent.parent

WLLAMA_VERSION = "3.13.0"
WLLAMA_URL = f"https://registry.npmjs.org/@wllama/wllama/-/wllama-{WLLAMA_VERSION}.tgz"
# The npm registry's published SHA-512 of the tarball.
WLLAMA_SHA512 = "ZvoRdQAn+E+18EvQ9qS036gudiI9rbZRBJgG/qNICPPwrA0Y6SMMdbziz/j7K/0WxcbJlhaRraVIYsnEy732NA=="
WLLAMA_FILES = {"package/esm/index.js": "index.js", "package/esm/wasm/wllama.wasm": "wllama.wasm"}



def fetch_wllama() -> None:
    vendor = HERE / "vendor"
    if all((vendor / name).exists() for name in WLLAMA_FILES.values()) and (vendor / "VERSION").read_text().strip() == WLLAMA_VERSION:
        print(f"wllama {WLLAMA_VERSION}: already in vendor/")
        return
    print(f"Downloading wllama {WLLAMA_VERSION}...")
    data = urllib.request.urlopen(WLLAMA_URL, timeout=120).read()
    digest = base64.b64encode(hashlib.sha512(data).digest()).decode()
    if digest != WLLAMA_SHA512:
        raise SystemExit(f"error: wllama checksum mismatch (got {digest})")
    vendor.mkdir(exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(data)) as tar:
        for member, name in WLLAMA_FILES.items():
            (vendor / name).write_bytes(tar.extractfile(member).read())
    (vendor / "VERSION").write_text(WLLAMA_VERSION + "\n")
    print("wllama: checksum OK, files in vendor/")


def write_config() -> None:
    # The memory note is per user: the extension adds the user's own note after
    # memory_header, in place of the training data's example.
    spec = json.loads((REPO_ROOT / "spec" / "wilo_prompt.json").read_text())
    registry = yaml.safe_load((REPO_ROOT / "models" / "registry.yaml").read_text())["models"]
    models = []
    for key, model in registry.items():
        gguf = model["gguf"]
        models.append({
            "key": key,
            "name": model["display_name"],
            "url": f"https://huggingface.co/{gguf['repo']}/resolve/{gguf['revision']}/{gguf['file']}",
            "sizeBytes": gguf["size_bytes"],
        })
    config = {
        "rules": spec["rules"],
        "memoryHeader": spec["memory_header"],
        "maxTokens": spec["max_tokens"],
        "models": models,
        # Best judgment of the base models in our browser tests (README).
        "defaultModel": "llama3.2-3b",
    }
    out = HERE / "generated"
    out.mkdir(exist_ok=True)
    (out / "config.js").write_text(
        "// Generated by apps/extension/setup.py from spec/wilo_prompt.json and\n"
        "// models/registry.yaml. Don't edit by hand: re-run the script.\n"
        f"export const CONFIG = {json.dumps(config, indent=2, ensure_ascii=False)};\n"
    )
    print(f"generated/config.js written ({len(models)} models)")


# Developer-only files that testers don't need.
NOT_SHIPPED = {"setup.py", "dev", "dist", ".gitignore", "README.md", "guide"}
GUIDE = HERE / "guide" / "tester-guide.html"


def guide_single_file() -> str:
    """The tester guide with its pictures built in, so it's one file to send."""
    import re

    html = GUIDE.read_text()

    def inline(match):
        data = base64.b64encode((GUIDE.parent / match.group(1)).read_bytes()).decode()
        return f'src="data:image/png;base64,{data}"'

    return re.sub(r'src="(img/[^"]+\.png)"', inline, html)


def make_zip() -> None:
    version = json.loads((HERE / "manifest.json").read_text())["version"]
    out = HERE / "dist" / f"wilo-extension-{version}.zip"
    out.parent.mkdir(exist_ok=True)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for path in sorted(HERE.rglob("*")):
            rel = path.relative_to(HERE)
            if path.is_file() and rel.parts[0] not in NOT_SHIPPED and "__pycache__" not in rel.parts:
                z.write(path, Path("wilo-extension") / rel)
        # The guide sits next to the folder, so testers see it right after unzipping.
        z.writestr("Wilo tester guide.html", guide_single_file())
    print(f"Packed {out.relative_to(REPO_ROOT)} ({out.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Prepare the Wilo extension for Chrome.")
    parser.add_argument("--zip", action="store_true", help="also pack it into dist/ for testers")
    args = parser.parse_args()
    fetch_wllama()
    write_config()
    if args.zip:
        make_zip()
